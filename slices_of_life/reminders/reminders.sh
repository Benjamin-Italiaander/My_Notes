#!/usr/bin/env bash
# reminders.sh — manage the reminders (every reminder in English and Dutch)
#
#   ./reminders.sh                 rebuild the index (README.md) and every reminder's README.md
#   ./reminders.sh new "English title" ["Nederlandse titel"] [category]
#                                  create a new reminder folder with en.md + nl.md
#                                  templates, then rebuild the index
#   ./reminders.sh help
#
# Layout:
#   some_slug/en.md        English version   (you write this)
#   some_slug/nl.md        Dutch version     (you write this)
#   some_slug/README.md    GENERATED landing page with links to both languages
#   README.md              intro text + GENERATED index between the
#                          "reminder-index" markers (text outside them is kept)
#
# Each en.md / nl.md starts with front matter:
#   ---
#   title: "How to Say No"
#   date: 2016-11-22
#   description: "How to say no kindly and clearly."
#   category: "relationships"   # mindset | relationships | emotions | health | society | ...
#   translated_by_ai: true      # optional: this language version was translated by AI
#   translated_from: "nl"       # optional: the language of the original
#   ---
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"

INDEX="README.md"
START="<!-- reminder-index:start -->"
END="<!-- reminder-index:end -->"

# Category slug -> heading. Unknown categories are shown as-is.
category_label() {
    case "$1" in
        mindset)       echo "🧭 Mindset · Mindset" ;;
        relationships) echo "💞 Relationships · Relaties" ;;
        emotions)      echo "🌊 Emotions & self-care · Emoties & zelfzorg" ;;
        health)        echo "🌱 Health · Gezondheid" ;;
        society)       echo "📰 Society & language · Maatschappij & taal" ;;
        *)             echo "📁 ${1^}" ;;
    esac
}
# Order of categories in the index (others follow alphabetically)
CATEGORY_ORDER="mindset relationships emotions health society"

# Read a front-matter field from a markdown file (empty if missing)
fm() {
    [ -f "$1" ] || return 0
    awk -v k="$2" '
        NR == 1 && $0 != "---" { exit }
        NR > 1 && $0 == "---"  { exit }
        index($0, k ":") == 1 {
            v = substr($0, length(k) + 2); sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
            if (v ~ /^".*"$/ || v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
            gsub(/\\"/, "\"", v); print v; exit
        }' "$1"
}

# every sub folder that holds an en.md or nl.md
reminder_dirs() {
    find . -mindepth 2 -maxdepth 2 \( -name en.md -o -name nl.md \) -printf '%h\n' \
        | sed 's|^\./||' | sort -u
}

yaml_str() { printf '"%s"' "$(printf '%s' "$1" | sed 's/"/\\"/g')"; }

# 🤖 marker for AI-translated versions
ai_mark() { [ "$(fm "$1" translated_by_ai)" = "true" ] && printf ' 🤖' || true; }

link() {  # link FILE TITLE MISSING_TEXT
    if [ -f "$1" ]; then printf '[%s](%s)%s' "${2:-$1}" "$1" "$(ai_mark "$1")"
    else printf '_%s_' "$3"; fi
}

# ---------------------------------------------------------------- index
build_index() {
    local tmp rows d en nl cat n
    tmp="$(mktemp)"; rows="$(mktemp)"
    n=0
    for d in $(reminder_dirs); do
        en="$(fm "$d/en.md" title)"
        nl="$(fm "$d/nl.md" title)"
        cat="$(fm "$d/en.md" category)"; [ -n "$cat" ] || cat="$(fm "$d/nl.md" category)"
        [ -n "$cat" ] || cat="other"
        [ -f "$d/en.md" ] || echo "⚠️  $d: no English version (en.md)" >&2
        [ -f "$d/nl.md" ] || echo "⚠️  $d: no Dutch version (nl.md)" >&2
        write_reminder_readme "$d" "$en" "$nl"
        printf '%s\t%s\t%s\t%s\n' "$cat" "$d" "$en" "$nl" >> "$rows"
        n=$((n + 1))
    done

    {
        echo "$START"
        echo "<!-- Generated by reminders.sh — do not edit between these markers. -->"
        echo
        echo "## 📚 Index"
        echo
        echo "$n reminders, each in 🇬🇧 English and 🇳🇱 Nederlands. 🤖 = translated with AI · met AI vertaald."
        local c order seen=" "
        order="$CATEGORY_ORDER $(cut -f1 "$rows" | sort -u | tr '\n' ' ')"
        for c in $order; do
            case "$seen" in *" $c "*) continue ;; esac
            seen="$seen$c "
            grep -q "^$c	" "$rows" || continue
            echo
            echo "### $(category_label "$c")"
            echo
            echo "| 🇬🇧 English | 🇳🇱 Nederlands |"
            echo "|---|---|"
            while IFS=$'\t' read -r _ d en nl; do
                printf '| %s | %s |\n' \
                    "$(link "$d/en.md" "$en" "not translated yet")" \
                    "$(link "$d/nl.md" "$nl" "nog niet vertaald")"
            done < <(awk -F'\t' -v c="$c" '$1 == c' "$rows" | sort -t$'\t' -k3,3)
        done
        echo
        echo "$END"
    } > "$tmp"

    if [ ! -f "$INDEX" ]; then
        printf -- '---\ntitle: "Reminders"\ndate: %s\ndescription: "Reminders about living well."\n---\n\n' "$(date +%F)" > "$INDEX"
    fi
    if grep -qF "$START" "$INDEX"; then
        awk -v s="$START" -v e="$END" -v f="$tmp" '
            $0 == s { while ((getline l < f) > 0) print l; skip = 1; next }
            $0 == e { skip = 0; next }
            !skip' "$INDEX" > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    else
        { cat "$INDEX"; echo; cat "$tmp"; } > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    fi
    rm -f "$tmp" "$rows"
    echo "Index updated: $n reminders → $PWD/$INDEX"
}

write_reminder_readme() {  # DIR EN NL
    local d="$1" en="$2" nl="$3" main date desc
    main="${en:-$nl}"
    date="$(fm "$d/en.md" date)"; [ -n "$date" ] || date="$(fm "$d/nl.md" date)"
    desc="$(fm "$d/en.md" description)"; [ -n "$desc" ] || desc="$(fm "$d/nl.md" description)"
    {
        echo "---"
        echo "title: $(yaml_str "$main")"
        [ -n "$date" ] && echo "date: $date"
        echo "description: $(yaml_str "${desc:-$main, in English and Dutch.}")"
        echo "linkTitle: $(yaml_str "$main")"
        echo "---"
        echo "<!-- Generated by reminders.sh — edit en.md / nl.md instead of this file. -->"
        echo
        echo "# $main"
        [ -n "$nl" ] && [ "$nl" != "$main" ] && { echo; echo "*🇳🇱 $nl*"; }
        echo
        if [ -f "$d/en.md" ]; then echo "- 🇬🇧 **[Read it in English](en.md)**$(ai_mark "$d/en.md")"; fi
        if [ -f "$d/nl.md" ]; then echo "- 🇳🇱 **[Lees het in het Nederlands](nl.md)**$(ai_mark "$d/nl.md")"; fi
        echo
        echo "[← All reminders / Alle reminders](../README.md)"
    } > "$d/README.md"
}

# ---------------------------------------------------------------- new
slugify() {
    printf '%s' "$1" | iconv -f utf-8 -t ascii//TRANSLIT 2>/dev/null \
        | tr '[:upper:]' '[:lower:]' | sed -E 's/&/and/g; s/[^a-z0-9]+/_/g; s/^_+|_+$//g' | cut -c1-50
}

new_reminder() {
    local en="${1:-}" nl="${2:-}" cat="${3:-mindset}" d
    [ -n "$en" ] || { echo "Usage: $0 new \"English title\" [\"Nederlandse titel\"] [category]" >&2; exit 1; }
    [ -n "$nl" ] || nl="$en"
    d="$(slugify "$en")"
    [ ! -e "$d" ] || { echo "$d already exists" >&2; exit 1; }
    mkdir "$d"
    cat > "$d/en.md" <<EOF
---
title: $(yaml_str "$en")
date: $(date +%F)
description: "One sentence about this reminder."
category: $(yaml_str "$cat")
---

# $en

…
EOF
    cat > "$d/nl.md" <<EOF
---
title: $(yaml_str "$nl")
date: $(date +%F)
description: "Eén zin over deze reminder."
category: $(yaml_str "$cat")
---

# $nl

…
EOF
    echo "Created $d/ (en.md + nl.md)."
    build_index
}

case "${1:-index}" in
    index)          build_index ;;
    new)            shift; new_reminder "$@" ;;
    -h|--help|help) sed -n '2,25p' "$0" ;;
    *)              echo "Unknown command '$1'. Try: $0 help" >&2; exit 1 ;;
esac

#!/usr/bin/env bash
# quotes.sh — manage the quotes (every quote in English and Dutch)
#
#   ./quotes.sh                 rebuild the index (README.md) and every quote's README.md
#   ./quotes.sh new "English title" ["Nederlandse titel"] ["Who said it"]
#                               create the next numbered quote with en.md + nl.md
#                               templates, then rebuild the index
#   ./quotes.sh help
#
# Layout:
#   NNN_some_slug/en.md        English version   (you write this)
#   NNN_some_slug/nl.md        Dutch version     (you write this)
#   NNN_some_slug/README.md    GENERATED landing page with links to both languages
#   README.md                  intro text + GENERATED index between the
#                              "quote-index" markers (text outside them is kept)
#
# Each en.md / nl.md starts with front matter:
#   ---
#   title: "Trust and Deception"
#   date: 2016-02-12
#   description: "Do not fear the enemies who attack you, fear the friends who flatter you."
#   source: "Álvaro Obregón"     # optional: who said or wrote it
#   translated_by_ai: true       # optional: this language version was translated by AI
#   translated_from: "en"        # optional: the language of the original
#   ---
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"

INDEX="README.md"
START="<!-- quote-index:start -->"
END="<!-- quote-index:end -->"

fm() {  # read a front-matter field (empty if missing)
    [ -f "$1" ] || return 0
    awk -v k="$2" '
        NR == 1 && $0 != "---" { exit }
        NR > 1 && $0 == "---"  { exit }
        index($0, k ":") == 1 {
            v = substr($0, length(k) + 2); sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
            if (v ~ /^".*"$/ || v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
            gsub(/\\"/, "\"", v); print v; exit
        }' "$1"
}

quote_dirs() { find . -maxdepth 1 -type d -regex '\./[0-9][0-9][0-9]_.*' | sed 's|^\./||' | sort; }

yaml_str() { printf '"%s"' "$(printf '%s' "$1" | sed 's/"/\\"/g')"; }

ai_mark() { [ "$(fm "$1" translated_by_ai)" = "true" ] && printf ' 🤖' || true; }

link() {  # link FILE TITLE MISSING_TEXT
    if [ -f "$1" ]; then printf '[%s](%s)%s' "${2:-$1}" "$1" "$(ai_mark "$1")"
    else printf '_%s_' "$3"; fi
}

# ---------------------------------------------------------------- index
build_index() {
    local tmp d en nl src n=0
    tmp="$(mktemp)"
    {
        echo "$START"
        echo "<!-- Generated by quotes.sh — do not edit between these markers. -->"
        echo
        echo "## 📚 Index"
        echo
        echo "$(quote_dirs | wc -l | tr -d ' ') quotes, each in 🇬🇧 English and 🇳🇱 Nederlands. 🤖 = translated with AI · met AI vertaald."
        echo
        echo "| # | 🇬🇧 English | 🇳🇱 Nederlands | By · Door |"
        echo "|---|---|---|---|"
        for d in $(quote_dirs); do
            en="$(fm "$d/en.md" title)"
            nl="$(fm "$d/nl.md" title)"
            src="$(fm "$d/en.md" source)"; [ -n "$src" ] || src="$(fm "$d/nl.md" source)"
            [ -f "$d/en.md" ] || echo "⚠️  $d: no English version (en.md)" >&2
            [ -f "$d/nl.md" ] || echo "⚠️  $d: no Dutch version (nl.md)" >&2
            write_quote_readme "$d" "$en" "$nl" "$src"
            printf '| %s | %s | %s | %s |\n' "${d%%_*}" \
                "$(link "$d/en.md" "$en" "not translated yet")" \
                "$(link "$d/nl.md" "$nl" "nog niet vertaald")" "${src:-–}"
            n=$((n + 1))
        done
        echo
        echo "$END"
    } > "$tmp"

    if [ ! -f "$INDEX" ]; then
        printf -- '---\ntitle: "Quotes for Life"\ndate: %s\ndescription: "Quotes I want to remember."\n---\n\n' "$(date +%F)" > "$INDEX"
    fi
    if grep -qF "$START" "$INDEX"; then
        awk -v s="$START" -v e="$END" -v f="$tmp" '
            $0 == s { while ((getline l < f) > 0) print l; skip = 1; next }
            $0 == e { skip = 0; next }
            !skip' "$INDEX" > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    else
        { cat "$INDEX"; echo; cat "$tmp"; } > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    fi
    rm -f "$tmp"
    echo "Index updated: $n quotes → $PWD/$INDEX"
}

write_quote_readme() {  # DIR EN NL SOURCE
    local d="$1" en="$2" nl="$3" src="$4" main date desc
    main="${en:-$nl}"
    date="$(fm "$d/en.md" date)"; [ -n "$date" ] || date="$(fm "$d/nl.md" date)"
    desc="$(fm "$d/en.md" description)"; [ -n "$desc" ] || desc="$(fm "$d/nl.md" description)"
    {
        echo "---"
        echo "title: $(yaml_str "$main")"
        [ -n "$date" ] && echo "date: $date"
        echo "description: $(yaml_str "${desc:-$main, in English and Dutch.}")"
        echo "linkTitle: $(yaml_str "${d%%_*} $main")"
        echo "---"
        echo "<!-- Generated by quotes.sh — edit en.md / nl.md instead of this file. -->"
        echo
        echo "# $main"
        [ -n "$nl" ] && [ "$nl" != "$main" ] && { echo; echo "*🇳🇱 $nl*"; }
        [ -n "$src" ] && { echo; echo "— $src"; }
        echo
        if [ -f "$d/en.md" ]; then echo "- 🇬🇧 **[Read it in English](en.md)**$(ai_mark "$d/en.md")"; fi
        if [ -f "$d/nl.md" ]; then echo "- 🇳🇱 **[Lees het in het Nederlands](nl.md)**$(ai_mark "$d/nl.md")"; fi
        echo
        echo "[← All quotes / Alle citaten](../README.md)"
    } > "$d/README.md"
}

# ---------------------------------------------------------------- new
slugify() {
    printf '%s' "$1" | iconv -f utf-8 -t ascii//TRANSLIT 2>/dev/null \
        | tr '[:upper:]' '[:lower:]' | sed -E 's/&/and/g; s/[^a-z0-9]+/_/g; s/^_+|_+$//g' | cut -c1-50
}

new_quote() {
    local en="${1:-}" nl="${2:-}" src="${3:-}" last num d
    [ -n "$en" ] || { echo "Usage: $0 new \"English title\" [\"Nederlandse titel\"] [\"Who said it\"]" >&2; exit 1; }
    [ -n "$nl" ] || nl="$en"
    last="$(quote_dirs | tail -1 | cut -c1-3)"
    num="$(printf '%03d' $((10#${last:-0} + 1)))"
    d="${num}_$(slugify "$en")"
    mkdir "$d"
    for lang in en nl; do
        local t="$en" desc="One sentence about this quote." quote="> *“…”*"
        [ "$lang" = nl ] && { t="$nl"; desc="Eén zin over dit citaat."; }
        {
            echo "---"
            echo "title: $(yaml_str "$t")"
            echo "date: $(date +%F)"
            echo "description: \"$desc\""
            [ -n "$src" ] && echo "source: $(yaml_str "$src")"
            echo "---"
            echo
            echo "$quote"
            [ -n "$src" ] && { echo; echo "— *$src*"; }
        } > "$d/$lang.md"
    done
    echo "Created $d/ (en.md + nl.md)."
    build_index
}

case "${1:-index}" in
    index)          build_index ;;
    new)            shift; new_quote "$@" ;;
    -h|--help|help) sed -n '2,25p' "$0" ;;
    *)              echo "Unknown command '$1'. Try: $0 help" >&2; exit 1 ;;
esac

#!/usr/bin/env bash
# recipes.sh — manage Benjamin's Culinary Logbook (English + Dutch recipes)
#
#   ./recipes.sh                 rebuild the index (README.md) and every recipe's README.md
#   ./recipes.sh new "English title" ["Nederlandse titel"] [category] [emoji]
#                                create the next numbered recipe with en.md + nl.md
#                                templates, then rebuild the index
#   ./recipes.sh help
#
# Layout:
#   NNN_some_slug/en.md      English recipe   (you write this)
#   NNN_some_slug/nl.md      Dutch recipe     (you write this)
#   NNN_some_slug/photo.png  optional photo (photo.jpg / .jpeg / .webp also work)
#   NNN_some_slug/README.md  GENERATED landing page with links to both languages
#   README.md                intro text + GENERATED index between the
#                            "recipe-index" markers (text outside them is kept)
#
# Each en.md / nl.md starts with front matter:
#   ---
#   title: "Lentils with Garam Masala"
#   date: 2016-09-22
#   description: "A simple, aromatic lentil dish with warm Indian spices."
#   emoji: "🍲"
#   category: "main"          # main | bowls | bread | soups | desserts | snacks | drinks | ...
#   ---
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"

INDEX="README.md"
START="<!-- recipe-index:start -->"
END="<!-- recipe-index:end -->"

# Category slug -> heading. Unknown categories are shown as-is.
category_label() {
    case "$1" in
        main)     echo "🍽️ Main dishes · Hoofdgerechten" ;;
        bowls)    echo "🥗 Bowls & salads · Bowls & salades" ;;
        bread)    echo "🍞 Bread & baking · Brood & bakken" ;;
        soups)    echo "🥣 Soups · Soepen" ;;
        desserts) echo "🍰 Desserts · Desserts" ;;
        snacks)   echo "🥨 Snacks · Snacks" ;;
        drinks)   echo "🥤 Drinks · Dranken" ;;
        *)        echo "📁 ${1^}" ;;
    esac
}
# Order of categories in the index (others follow alphabetically)
CATEGORY_ORDER="main bowls soups bread snacks desserts drinks"

# Read a front-matter field from a markdown file (empty if missing)
fm() {
    [ -f "$1" ] || return 0
    awk -v k="$2" '
        NR == 1 && $0 != "---" { exit }
        NR > 1 && $0 == "---"  { exit }
        index($0, k ":") == 1 {
            v = substr($0, length(k) + 2); sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
            if (v ~ /^".*"$/ || v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
            gsub(/\\"/, "\"", v); print v; exit
        }' "$1"
}

recipe_dirs() { find . -maxdepth 1 -type d -regex '\./[0-9][0-9][0-9]_.*' | sed 's|^\./||' | sort; }

photo_of() {
    local d="$1" f
    for f in photo.png photo.jpg photo.jpeg photo.webp; do
        [ -f "$d/$f" ] && { echo "$f"; return 0; }
    done
    return 0
}

yaml_str() { printf '"%s"' "$(printf '%s' "$1" | sed 's/"/\\"/g')"; }

# ---------------------------------------------------------------- index
build_index() {
    local tmp rows d num en nl emoji cat photo
    tmp="$(mktemp)"; rows="$(mktemp)"

    for d in $(recipe_dirs); do
        num="${d%%_*}"
        en="$(fm "$d/en.md" title)"
        nl="$(fm "$d/nl.md" title)"
        emoji="$(fm "$d/en.md" emoji)"; [ -n "$emoji" ] || emoji="$(fm "$d/nl.md" emoji)"
        cat="$(fm "$d/en.md" category)"; [ -n "$cat" ] || cat="$(fm "$d/nl.md" category)"
        [ -n "$cat" ] || cat="other"
        photo="$(photo_of "$d")"
        [ -f "$d/en.md" ] || echo "⚠️  $d: no English version (en.md)" >&2
        [ -f "$d/nl.md" ] || echo "⚠️  $d: no Dutch version (nl.md)" >&2

        write_recipe_readme "$d" "$en" "$nl" "$emoji" "$photo" \
            "$(fm "$d/en.md" date)" "$(fm "$d/en.md" description)"
        printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$cat" "$num" "$d" "$emoji" "$en" "$nl" >> "$rows"
    done

    # --- the index block
    {
        echo "$START"
        echo "<!-- Generated by recipes.sh — do not edit between these markers. -->"
        echo
        echo "## 📚 Index"
        echo
        echo "$(recipe_dirs | wc -l | tr -d ' ') recipes, each in 🇬🇧 English and 🇳🇱 Nederlands."
        local c order seen=" "
        order="$CATEGORY_ORDER $(cut -f1 "$rows" | sort -u | tr '\n' ' ')"
        for c in $order; do
            case "$seen" in *" $c "*) continue ;; esac
            seen="$seen$c "
            grep -q "^$c	" "$rows" || continue
            echo
            echo "### $(category_label "$c")"
            echo
            echo "| # | 🇬🇧 English | 🇳🇱 Nederlands |"
            echo "|---|---|---|"
            while IFS=$'\t' read -r _ num d emoji en nl; do
                printf '| %s | %s | %s |\n' "$num" \
                    "$(link "$d/en.md" "$emoji" "$en" "not translated yet")" \
                    "$(link "$d/nl.md" "$emoji" "$nl" "nog niet vertaald")"
            done < <(awk -F'\t' -v c="$c" '$1 == c' "$rows" | sort -t$'\t' -k2,2)
        done
        echo
        echo "$END"
    } > "$tmp"

    # --- put the block into README.md (replace between markers, or append)
    if [ ! -f "$INDEX" ]; then
        printf -- '---\ntitle: "Culinary Notes By Benjamin"\n---\n\n# 📖 Benjamin’s Culinary Logbook\n\n' > "$INDEX"
    fi
    if grep -qF "$START" "$INDEX"; then
        awk -v s="$START" -v e="$END" -v f="$tmp" '
            $0 == s { while ((getline l < f) > 0) print l; skip = 1; next }
            $0 == e { skip = 0; next }
            !skip' "$INDEX" > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    else
        { cat "$INDEX"; echo; cat "$tmp"; } > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
    fi
    rm -f "$tmp" "$rows"
    echo "Index updated: $(recipe_dirs | wc -l | tr -d ' ') recipes → $PWD/$INDEX"
}

link() {  # link FILE EMOJI TITLE MISSING_TEXT
    if [ -f "$1" ]; then printf '%s [%s](%s)' "$2" "${3:-$1}" "$1"
    else printf '_%s_' "$4"; fi
}

write_recipe_readme() {  # DIR EN NL EMOJI PHOTO DATE DESCRIPTION
    local d="$1" en="$2" nl="$3" emoji="$4" photo="$5" date="${6:-}" desc="${7:-}" main
    main="${en:-$nl}"
    {
        echo "---"
        echo "title: $(yaml_str "${emoji:+$emoji }$main")"
        [ -n "$date" ] && echo "date: $date"
        echo "description: $(yaml_str "${desc:-$main, in English and Dutch.}")"
        echo "linkTitle: $(yaml_str "$main")"
        echo "---"
        echo "<!-- Generated by recipes.sh — edit en.md / nl.md instead of this file. -->"
        echo
        echo "# ${emoji:+$emoji }$main"
        [ -n "$nl" ] && [ "$nl" != "$main" ] && { echo; echo "*🇳🇱 $nl*"; }
        echo
        if [ -f "$d/en.md" ]; then echo "- 🇬🇧 **[Read the recipe in English](en.md)**"; fi
        if [ -f "$d/nl.md" ]; then echo "- 🇳🇱 **[Lees het recept in het Nederlands](nl.md)**"; fi
        [ -n "$photo" ] && { echo; echo "![$main]($photo)"; }
        echo
        echo "[← All recipes / Alle recepten](../README.md)"
    } > "$d/README.md"
}

# ---------------------------------------------------------------- new
slugify() {
    printf '%s' "$1" | iconv -f utf-8 -t ascii//TRANSLIT 2>/dev/null \
        | tr '[:upper:]' '[:lower:]' | sed -E 's/&/and/g; s/[^a-z0-9]+/_/g; s/^_+|_+$//g' | cut -c1-50
}

new_recipe() {
    local en="${1:-}" nl="${2:-}" cat="${3:-main}" emoji="${4:-🍽️}" last num d
    [ -n "$en" ] || { echo "Usage: $0 new \"English title\" [\"Nederlandse titel\"] [category] [emoji]" >&2; exit 1; }
    [ -n "$nl" ] || nl="$en"
    last="$(recipe_dirs | tail -1 | cut -c1-3)"
    num="$(printf '%03d' $((10#${last:-0} + 1)))"
    d="${num}_$(slugify "$en")"
    mkdir "$d"

    cat > "$d/en.md" <<EOF
---
title: $(yaml_str "$en")
date: $(date +%F)
description: "One sentence about this recipe."
emoji: $(yaml_str "$emoji")
category: $(yaml_str "$cat")
---

# $emoji $en

![$en](photo.png)

**Servings:** 4
**Prep time:** … minutes
**Cook time:** … minutes

---

## 🥗 Ingredients

- …

---

## 🔪 Instructions

1. …

---

## 💡 Tips

- …
EOF

    cat > "$d/nl.md" <<EOF
---
title: $(yaml_str "$nl")
date: $(date +%F)
description: "Eén zin over dit recept."
emoji: $(yaml_str "$emoji")
category: $(yaml_str "$cat")
---

# $emoji $nl

![$nl](photo.png)

**Porties:** 4
**Bereidingstijd:** … minuten
**Kooktijd:** … minuten

---

## 🥗 Ingrediënten

- …

---

## 🔪 Bereidingswijze

1. …

---

## 💡 Tips

- …
EOF
    echo "Created $d/ (en.md + nl.md). Add a photo as $d/photo.png (optional)."
    build_index
}

case "${1:-index}" in
    index)        build_index ;;
    new)          shift; new_recipe "$@" ;;
    -h|--help|help) sed -n '2,24p' "$0" ;;
    *)            echo "Unknown command '$1'. Try: $0 help" >&2; exit 1 ;;
esac

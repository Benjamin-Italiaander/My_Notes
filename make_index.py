#!/usr/bin/env python3
"""make_index.py — build a bilingual index of all notes in a folder.

    ./make_index.py Linux            index for Linux/
    ./make_index.py Linux math Misc  several folders at once

For each folder it writes a table of contents, grouped by sub folder, into the
folder's README.md and into its translation (nl.md or en.md), between the markers

    <!-- note-index:start -->
    <!-- note-index:end -->

Text outside the markers is kept; run the script again after adding notes.
Every note is listed once, with its English and Dutch version side by side.
Pairs are found through the translation's front matter:
    translated_by_ai: true
    translated_from: "en"
    original: "the_original.md"
"""
import os
import re
import sys

START = "<!-- note-index:start -->"
END = "<!-- note-index:end -->"
HERE = os.path.dirname(os.path.abspath(__file__))
ABBREV = {"cli", "ssh", "ssl", "kvm", "gpg", "rs232", "pam", "otp", "css", "html"}
NAMES = {"yubikey": "YubiKey", "gnupg": "GnuPG", "imagemagick": "ImageMagick"}   # special spellings


def front_matter(path):
    """Return the front matter of a markdown file as a dict of simple key: value pairs."""
    text = open(path, encoding="utf-8").read()
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    fm = {}
    for line in text[4:end].split("\n"):
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            v = m.group(2).strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
                v = v[1:-1]
            fm[m.group(1)] = v.replace('\\"', '"')
    return fm


def pretty(name):
    if name.lower() in NAMES:
        return NAMES[name.lower()]
    words = re.split(r"[_\-\s]+", name)
    return " ".join(w.upper() if w.lower() in ABBREV else w[:1].upper() + w[1:] for w in words if w)


def is_note(name):
    return name.lower().endswith(".md")


def collect(folder):
    """Return {subfolder: [ (en_path, en_title, en_ai, nl_path, nl_title, nl_ai) ]}."""
    groups = {}
    for dirpath, dirs, files in os.walk(folder):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        notes = [f for f in sorted(files) if is_note(f)]
        if not notes:
            continue
        rel_dir = os.path.relpath(dirpath, folder)
        fms = {f: front_matter(os.path.join(dirpath, f)) for f in notes}
        # translations, keyed by the original file name
        trans = {}
        for f, fm in fms.items():
            if fm.get("translated_by_ai") == "true" and fm.get("original"):
                trans[fm["original"].lower()] = f
        rows = []
        for f, fm in fms.items():
            if fm.get("translated_by_ai") == "true" and fm.get("original", "").lower() in {n.lower() for n in notes}:
                continue                              # listed next to its original
            if rel_dir == "." and f.lower() in ("readme.md", "nl.md", "en.md"):
                continue                              # the index page itself
            t = trans.get(f.lower())
            tfm = fms.get(t, {}) if t else {}
            orig_lang = tfm.get("translated_from") or ("en" if fm.get("translated_from") != "en" else "nl")
            title = fm.get("title") or pretty(os.path.splitext(f)[0])
            entry = (os.path.join(rel_dir, f), title, fm.get("translated_by_ai") == "true")
            other = (os.path.join(rel_dir, t), tfm.get("title", t), True) if t else (None, None, False)
            if orig_lang == "nl":
                entry, other = other, entry
            sort_key = 0 if f.lower() == "readme.md" else 1
            rows.append((sort_key, (entry[1] or other[1] or "").lower(), entry + other))
        rows.sort()
        groups[rel_dir] = [r[2] for r in rows]
    return groups


def link(path, title, ai, missing):
    if not path:
        return f"_{missing}_"
    path = os.path.normpath(path).replace(os.sep, "/").replace(" ", "%20")
    return f"[{title}]({path})" + (" 🤖" if ai else "")


def build_block(folder):
    groups = collect(folder)
    total = sum(len(v) for v in groups.values())
    out = [START, "<!-- Generated by make_index.py — do not edit between these markers. -->", "",
           "## 📚 Index", "",
           f"{total} notes, each in 🇬🇧 English and 🇳🇱 Nederlands. 🤖 = translated with AI · met AI vertaald."]
    for rel_dir in sorted(groups, key=lambda d: (d != ".", d.lower())):
        rows = groups[rel_dir]
        if not rows:
            continue
        heading = "General · Algemeen" if rel_dir == "." else " / ".join(pretty(p) for p in rel_dir.split(os.sep))
        out += ["", f"### {heading}", "", "| 🇬🇧 English | 🇳🇱 Nederlands |", "|---|---|"]
        for en_path, en_title, en_ai, nl_path, nl_title, nl_ai in rows:
            out.append(f"| {link(en_path, en_title, en_ai, 'not translated yet')} "
                       f"| {link(nl_path, nl_title, nl_ai, 'nog niet vertaald')} |")
    out += ["", END]
    return "\n".join(out), total


def insert(page, block):
    text = open(page, encoding="utf-8").read()
    if START in text and END in text:
        a = text.index(START)
        b = text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(page, "w", encoding="utf-8").write(text)


def main(folders):
    for name in folders:
        folder = os.path.join(HERE, name)
        if not os.path.isdir(folder):
            print(f"⚠️  {name}: not a folder"); continue
        block, total = build_block(folder)
        pages = [p for p in ("README.md", "nl.md", "en.md") if os.path.exists(os.path.join(folder, p))]
        if not pages:
            print(f"⚠️  {name}: no README.md to put the index in"); continue
        for p in pages:
            insert(os.path.join(folder, p), block)
        print(f"Index updated: {total} notes → {name}/{', '.join(pages)}")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] in ("-h", "--help", "help"):
        print(__doc__); sys.exit(0)
    main(args or ["Linux"])
